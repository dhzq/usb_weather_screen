display_panel_handles_t display_panel_init(void)
{
    display_panel_handles_t handles = { .io = NULL, .panel = NULL };

    const spi_line_config_t line_config = {
        .cs_io_type = IO_TYPE_GPIO,
        .cs_gpio_num = HAL_LCD_SPI_CS_PIN,
        .scl_io_type = IO_TYPE_GPIO,
        .scl_gpio_num = HAL_LCD_SPI_SCL_PIN,
        .sda_io_type = IO_TYPE_GPIO,
        .sda_gpio_num = HAL_LCD_SPI_SDA_PIN,
        .io_expander = NULL,
    };
    esp_lcd_panel_io_3wire_spi_config_t io_config = ST7701_PANEL_IO_3WIRE_SPI_CONFIG(line_config, 0);
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_3wire_spi(&io_config, &handles.io));

    esp_lcd_rgb_panel_config_t rgb_config = {
        .clk_src = LCD_CLK_SRC_DEFAULT,
        .timings = {
            .pclk_hz = 12 * 1000 * 1000,
            .h_res = HAL_DISPLAY_WIDTH,
            .v_res = HAL_DISPLAY_HEIGHT,
            .hsync_pulse_width = 10,
            .hsync_back_porch = 10,
            .hsync_front_porch = 10,
            .vsync_pulse_width = 10,
            .vsync_back_porch = 10,
            .vsync_front_porch = 10,
            .flags = {
                .pclk_active_neg = false,
            },
        },
        .data_width = 16,
        .bits_per_pixel = 16,
        .num_fbs = 2,
        .bounce_buffer_size_px = HAL_DISPLAY_WIDTH * 16,
        .psram_trans_align = 64,
        .hsync_gpio_num = HAL_LCD_HSYNC_PIN,
        .vsync_gpio_num = HAL_LCD_VSYNC_PIN,
        .de_gpio_num = HAL_LCD_DE_PIN,
        .pclk_gpio_num = HAL_LCD_PCLK_PIN,
        .disp_gpio_num = HAL_LCD_DISP_PIN,
        .data_gpio_nums = {
            HAL_LCD_DATA0_PIN, HAL_LCD_DATA1_PIN, HAL_LCD_DATA2_PIN, HAL_LCD_DATA3_PIN,
            HAL_LCD_DATA4_PIN, HAL_LCD_DATA5_PIN, HAL_LCD_DATA6_PIN, HAL_LCD_DATA7_PIN,
            HAL_LCD_DATA8_PIN, HAL_LCD_DATA9_PIN, HAL_LCD_DATA10_PIN, HAL_LCD_DATA11_PIN,
            HAL_LCD_DATA12_PIN, HAL_LCD_DATA13_PIN, HAL_LCD_DATA14_PIN, HAL_LCD_DATA15_PIN,
        },
        .flags = {
            .fb_in_psram = 1,
        },
    };

    st7701_vendor_config_t vendor_config = {
        .init_cmds = s_lcd_init_cmds,
        .init_cmds_size = sizeof(s_lcd_init_cmds) / sizeof(s_lcd_init_cmds[0]),
        .rgb_config = &rgb_config,
        .flags = {
            .mirror_by_cmd = 0,
            .enable_io_multiplex = 1,
        },
    };
    const esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = HAL_LCD_RESET_PIN,
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 18,
        .flags = {
            .reset_active_high = 0,
        },
        .vendor_config = &vendor_config,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_st7701(handles.io, &panel_config, &handles.panel));
    ESP_ERROR_CHECK(esp_lcd_panel_init(handles.panel));

    ESP_LOGI(TAG, "ST7701 panel initialized (%dx%d)", HAL_DISPLAY_WIDTH, HAL_DISPLAY_HEIGHT);
    return handles;
}
